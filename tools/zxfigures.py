for _name, _rows in FIGURES.items():
    assert len(_rows) == 12 and all(len(r) == 16 for r in _rows), _name


def mono(name):
    """-> (mask, ink) rows of 0/1: the mask is the figure and a ring of paper
    round it, the ink its '#'"""
    rows = FIGURES[name]
    h, w = len(rows), len(rows[0])

    def on(y, x):
        return 0 <= y < h and 0 <= x < w and rows[y][x] != '.'
    mask = [[1 if any(on(y + dy, x + dx) for dy in (-1, 0, 1) for dx in (-1, 0, 1)) else 0
             for x in range(w)] for y in range(h)]
    ink = [[1 if rows[y][x] == '#' else 0 for x in range(w)] for y in range(h)]
    return mask, ink
